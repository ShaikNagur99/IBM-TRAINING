public class Autoboxingandunboxing {
    public static void main(String[] args) {
        int f=20;
        Integer y=f;//autoboxing
        System.out.println(f);
        System.out.println(y);

        Integer u=50;
        int g=u;//autounboxing
        System.out.println(u);
        System.out.println(g);

    }
}
